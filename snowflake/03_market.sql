-- From Slack to Strategy — market data (fourth source)
-- INEGI DENUE establishments, loaded by MuleSoft (mulesoft/denue-market-loader).
-- Contact fields (phone, email, website) and legal name are deliberately NOT loaded:
-- they can identify individuals and the demo doesn't need them.
-- Adding this source to the agent was a connector decision, not an integration project.

USE ROLE ACCOUNTADMIN;

CREATE SCHEMA IF NOT EXISTS MD26_DB.MARKET COMMENT = 'Market data: INEGI DENUE establishments';

-- MuleSoft bulk-inserts here, then MERGEs into ESTABLISHMENTS (Snowflake doesn't enforce PKs).
CREATE TABLE IF NOT EXISTS MD26_DB.MARKET.ESTABLISHMENTS_STAGE (
  DENUE_ID        VARCHAR(20),
  CLEE            VARCHAR(40),
  NAME            VARCHAR(500),
  ACTIVITY_CODE   VARCHAR(10),
  ACTIVITY_CLASS  VARCHAR(255),
  SEARCH_TERM     VARCHAR(50),
  STRATUM         VARCHAR(50),
  BUSINESS_TYPE   VARCHAR(30),
  STREET          VARCHAR(255),
  EXT_NUMBER      VARCHAR(30),
  NEIGHBORHOOD    VARCHAR(255),
  POSTAL_CODE     VARCHAR(10),
  LOCALITY        VARCHAR(150),
  MUNICIPALITY    VARCHAR(150),
  STATE_CODE      VARCHAR(2),
  STATE_NAME      VARCHAR(100),
  REGION          VARCHAR(20),
  LATITUDE        NUMBER(11,8),
  LONGITUDE       NUMBER(11,8),
  LOADED_AT       TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS MD26_DB.MARKET.ESTABLISHMENTS (
  DENUE_ID        VARCHAR(20)   NOT NULL PRIMARY KEY,
  CLEE            VARCHAR(40),
  NAME            VARCHAR(500),
  ACTIVITY_CODE   VARCHAR(10),
  ACTIVITY_CLASS  VARCHAR(255),
  SEARCH_TERM     VARCHAR(50),
  STRATUM         VARCHAR(50),
  BUSINESS_TYPE   VARCHAR(30),
  STREET          VARCHAR(255),
  EXT_NUMBER      VARCHAR(30),
  NEIGHBORHOOD    VARCHAR(255),
  POSTAL_CODE     VARCHAR(10),
  LOCALITY        VARCHAR(150),
  MUNICIPALITY    VARCHAR(150),
  STATE_CODE      VARCHAR(2),
  STATE_NAME      VARCHAR(100),
  REGION          VARCHAR(20),
  LATITUDE        NUMBER(11,8),
  LONGITUDE       NUMBER(11,8),
  SOURCE_SYSTEM   VARCHAR(30)   DEFAULT 'INEGI_DENUE',
  LOADED_AT       TIMESTAMP_NTZ,
  LAST_MODIFIED   TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

GRANT USAGE ON SCHEMA MD26_DB.MARKET TO ROLE MD26_LOADER;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES    IN SCHEMA MD26_DB.MARKET TO ROLE MD26_LOADER;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN SCHEMA MD26_DB.MARKET TO ROLE MD26_LOADER;

-- Data Cloud reads the curated table only, never the staging table.
GRANT USAGE ON SCHEMA MD26_DB.MARKET TO ROLE MD26_ZEROCOPY_READER;
GRANT SELECT ON TABLE MD26_DB.MARKET.ESTABLISHMENTS TO ROLE MD26_ZEROCOPY_READER;
