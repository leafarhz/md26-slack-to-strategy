-- From Slack to Strategy — load the synthetic ERP and Jira data from demo/data/*.csv
-- Run from the repo root:
--   snow sql -f snowflake/04_load_demo_data.sql -D "data_dir=$(pwd)/demo/data"
-- Idempotent: each table is truncated and reloaded.
-- (Market data is loaded separately by MuleSoft: mulesoft/denue-market-loader.)

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE MD26_WH;
USE SCHEMA MD26_DB.ERP;

CREATE OR REPLACE TEMPORARY STAGE MD26_DB.ERP.MD26_LOAD;
CREATE OR REPLACE TEMPORARY FILE FORMAT MD26_DB.ERP.MD26_CSV
  TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = TRUE NULL_IF = ('') ENCODING = 'UTF8';

PUT 'file://&{data_dir}/erp_customers.csv'         @MD26_LOAD AUTO_COMPRESS = TRUE OVERWRITE = TRUE;
PUT 'file://&{data_dir}/erp_sales_orders.csv'      @MD26_LOAD AUTO_COMPRESS = TRUE OVERWRITE = TRUE;
PUT 'file://&{data_dir}/erp_invoices.csv'          @MD26_LOAD AUTO_COMPRESS = TRUE OVERWRITE = TRUE;
PUT 'file://&{data_dir}/erp_quarterly_targets.csv' @MD26_LOAD AUTO_COMPRESS = TRUE OVERWRITE = TRUE;
PUT 'file://&{data_dir}/jira_epics.csv'            @MD26_LOAD AUTO_COMPRESS = TRUE OVERWRITE = TRUE;
PUT 'file://&{data_dir}/jira_issues.csv'           @MD26_LOAD AUTO_COMPRESS = TRUE OVERWRITE = TRUE;
PUT 'file://&{data_dir}/zendesk_tickets.csv'       @MD26_LOAD AUTO_COMPRESS = TRUE OVERWRITE = TRUE;

TRUNCATE TABLE MD26_DB.ERP.CUSTOMERS;
COPY INTO MD26_DB.ERP.CUSTOMERS (CUSTOMER_ID, DISPLAY_NAME, ACTIVITY_CODE, ACTIVITY_CLASS, STRATUM,
  STATE_CODE, STATE_NAME, MUNICIPALITY, LATITUDE, LONGITUDE, SEGMENT, REGION, CUSTOMER_SINCE)
  FROM @MD26_LOAD/erp_customers.csv.gz FILE_FORMAT = (FORMAT_NAME = 'MD26_DB.ERP.MD26_CSV');
UPDATE MD26_DB.ERP.CUSTOMERS SET SOURCE_SYSTEM = 'SYNTHETIC_ERP';

TRUNCATE TABLE MD26_DB.ERP.SALES_ORDERS;
COPY INTO MD26_DB.ERP.SALES_ORDERS (ORDER_ID, CUSTOMER_ID, ORDER_DATE, FISCAL_QUARTER, PRODUCT,
  AMOUNT_MXN, STATUS, PROMISED_DATE, DELIVERED_DATE, EPIC_KEY)
  FROM @MD26_LOAD/erp_sales_orders.csv.gz FILE_FORMAT = (FORMAT_NAME = 'MD26_DB.ERP.MD26_CSV');

TRUNCATE TABLE MD26_DB.ERP.INVOICES;
COPY INTO MD26_DB.ERP.INVOICES (INVOICE_ID, ORDER_ID, CUSTOMER_ID, ISSUE_DATE, DUE_DATE,
  AMOUNT_MXN, STATUS, PAID_DATE)
  FROM @MD26_LOAD/erp_invoices.csv.gz FILE_FORMAT = (FORMAT_NAME = 'MD26_DB.ERP.MD26_CSV');

TRUNCATE TABLE MD26_DB.ERP.QUARTERLY_TARGETS;
COPY INTO MD26_DB.ERP.QUARTERLY_TARGETS (TARGET_ID, FISCAL_QUARTER, REGION, BOOKINGS_TARGET_MXN, GO_LIVES_TARGET)
  FROM @MD26_LOAD/erp_quarterly_targets.csv.gz FILE_FORMAT = (FORMAT_NAME = 'MD26_DB.ERP.MD26_CSV');

TRUNCATE TABLE MD26_DB.JIRA.EPICS;
COPY INTO MD26_DB.JIRA.EPICS (EPIC_KEY, NAME, CUSTOMER_ID, ORDER_ID, REGION, TARGET_GO_LIVE, STATUS)
  FROM @MD26_LOAD/jira_epics.csv.gz FILE_FORMAT = (FORMAT_NAME = 'MD26_DB.ERP.MD26_CSV');

TRUNCATE TABLE MD26_DB.JIRA.ISSUES;
COPY INTO MD26_DB.JIRA.ISSUES (ISSUE_KEY, PROJECT, EPIC_KEY, CUSTOMER_ID, SUMMARY, ISSUE_TYPE, PRIORITY,
  STATUS, IS_BLOCKER, BLOCKED_BY, BLOCKED_REASON, ASSIGNEE, CREATED_AT, DUE_DATE, RESOLVED_AT)
  FROM @MD26_LOAD/jira_issues.csv.gz FILE_FORMAT = (FORMAT_NAME = 'MD26_DB.ERP.MD26_CSV');

-- Zendesk (requires snowflake/06_support.sql)
TRUNCATE TABLE MD26_DB.SUPPORT.ZENDESK_TICKETS;
COPY INTO MD26_DB.SUPPORT.ZENDESK_TICKETS (TICKET_ID, ORGANIZATION_EXTERNAL_ID, ORGANIZATION_NAME, SUBJECT,
  PRIORITY, STATUS, CHANNEL, CREATED_AT, SOLVED_AT)
  FROM @MD26_LOAD/zendesk_tickets.csv.gz FILE_FORMAT = (FORMAT_NAME = 'MD26_DB.ERP.MD26_CSV');
