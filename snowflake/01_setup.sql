-- From Slack to Strategy — Snowflake setup
-- Run as ACCOUNTADMIN. Idempotent.
--
-- Two roles, two jobs. This split is the first link of the permission chain:
--   MD26_LOADER          writes   (MuleSoft loads the "ERP" and "Jira" data)
--   MD26_ZEROCOPY_READER reads    (Data Cloud federates through Zero Copy)
-- Data Cloud never gets write access to the system of record.

CREATE WAREHOUSE IF NOT EXISTS MD26_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'MD26 demo — loads and Zero Copy queries';

CREATE DATABASE IF NOT EXISTS MD26_DB COMMENT = 'MD26 demo — enterprise systems of record';
CREATE SCHEMA IF NOT EXISTS MD26_DB.ERP  COMMENT = 'ERP: customers, orders, invoices, targets';
CREATE SCHEMA IF NOT EXISTS MD26_DB.JIRA COMMENT = 'Jira: implementation projects and issues';

CREATE ROLE IF NOT EXISTS MD26_LOADER          COMMENT = 'MuleSoft ingestion — read/write';
CREATE ROLE IF NOT EXISTS MD26_ZEROCOPY_READER COMMENT = 'Data Cloud Zero Copy — read only';
GRANT ROLE MD26_LOADER          TO ROLE SYSADMIN;
GRANT ROLE MD26_ZEROCOPY_READER TO ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE MD26_WH TO ROLE MD26_LOADER;
GRANT USAGE ON WAREHOUSE MD26_WH TO ROLE MD26_ZEROCOPY_READER;
GRANT USAGE ON DATABASE MD26_DB  TO ROLE MD26_LOADER;
GRANT USAGE ON DATABASE MD26_DB  TO ROLE MD26_ZEROCOPY_READER;

GRANT USAGE ON SCHEMA MD26_DB.ERP  TO ROLE MD26_LOADER;
GRANT USAGE ON SCHEMA MD26_DB.JIRA TO ROLE MD26_LOADER;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES    IN SCHEMA MD26_DB.ERP  TO ROLE MD26_LOADER;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN SCHEMA MD26_DB.ERP  TO ROLE MD26_LOADER;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES    IN SCHEMA MD26_DB.JIRA TO ROLE MD26_LOADER;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN SCHEMA MD26_DB.JIRA TO ROLE MD26_LOADER;

GRANT USAGE ON SCHEMA MD26_DB.ERP  TO ROLE MD26_ZEROCOPY_READER;
GRANT USAGE ON SCHEMA MD26_DB.JIRA TO ROLE MD26_ZEROCOPY_READER;
GRANT SELECT ON ALL TABLES    IN SCHEMA MD26_DB.ERP  TO ROLE MD26_ZEROCOPY_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA MD26_DB.ERP  TO ROLE MD26_ZEROCOPY_READER;
GRANT SELECT ON ALL TABLES    IN SCHEMA MD26_DB.JIRA TO ROLE MD26_ZEROCOPY_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA MD26_DB.JIRA TO ROLE MD26_ZEROCOPY_READER;
GRANT SELECT ON ALL VIEWS     IN SCHEMA MD26_DB.ERP  TO ROLE MD26_ZEROCOPY_READER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA MD26_DB.ERP  TO ROLE MD26_ZEROCOPY_READER;
GRANT SELECT ON ALL VIEWS     IN SCHEMA MD26_DB.JIRA TO ROLE MD26_ZEROCOPY_READER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA MD26_DB.JIRA TO ROLE MD26_ZEROCOPY_READER;

-- Service users (key-pair auth only, no passwords). Public keys are set later
-- with: ALTER USER <name> SET RSA_PUBLIC_KEY = '...';
CREATE USER IF NOT EXISTS MD26_MULE_SVC
  TYPE = SERVICE DEFAULT_ROLE = MD26_LOADER DEFAULT_WAREHOUSE = MD26_WH
  COMMENT = 'MuleSoft ingestion service user';
CREATE USER IF NOT EXISTS MD26_DATACLOUD_SVC
  TYPE = SERVICE DEFAULT_ROLE = MD26_ZEROCOPY_READER DEFAULT_WAREHOUSE = MD26_WH
  COMMENT = 'Salesforce Data Cloud Zero Copy service user';
GRANT ROLE MD26_LOADER          TO USER MD26_MULE_SVC;
GRANT ROLE MD26_ZEROCOPY_READER TO USER MD26_DATACLOUD_SVC;
